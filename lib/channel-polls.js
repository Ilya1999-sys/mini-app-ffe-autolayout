function pollForUtcDate(date) {
  return POLLS.find((poll) => poll.date === date) || null;
}

function validatePolls() {
  const dates = new Set();
  for (const poll of POLLS) {
    if (!/^\d{4}-\d{2}-\d{2}$/.test(poll.date) || dates.has(poll.date)) {
      throw new Error("Повторяется или неверна дата опроса");
    }
    dates.add(poll.date);
    const day = new Date(`${poll.date}T07:00:00Z`);
    if (day.getUTCDay() !== 2 || day.toISOString().slice(0, 10) !== poll.date) {
      throw new Error("Опрос назначен не на вторник");
    }
    if (poll.question.length < 1 || poll.question.length > 300 || poll.options.length < 2 || poll.options.length > 12) {
      throw new Error("Некорректная длина опроса");
    }
    if (poll.options.some((option) => option.length < 1 || option.length > 100)) {
      throw new Error("Некорректная длина варианта ответа");
    }
  }
}

